"""Standalone aggregator — refresh _master_comparison.{csv,md} after each
experiment finishes.

Walks `<output_root>/<exp_id>__seed<seed>/summary.json` for every completed
run, then writes the headline-metrics comparison table sorted by
`collapse_indicator` (ascending — worse first) then `final_macro` for
grounding (descending — better first).

Idempotent: safe to re-run any time. In-progress runs (missing summary.json)
are skipped with a log line.

Usage:
    python -m qwenvl.experiments.aggregate --output_root output/curriculum_v2_exp
"""

from __future__ import annotations

import argparse
import csv
import glob
import json
import os
import re
from typing import Dict, List, Optional, Tuple

# Column order for the master comparison.
HEADLINE_METRICS = ["answer_acc", "view_acc", "grounding_acc@0.8",
                    "grounding_format_valid"]


_RUN_DIR_RE = re.compile(r"^(?P<exp_id>[^/]+)__seed(?P<seed>\d+)$")


def discover_runs(output_root: str) -> List[Tuple[str, int, str, dict]]:
    """Return ordered [(exp_id, seed, run_dir, summary_dict), ...].

    Only returns runs that have a parseable summary.json. Sort order is by
    exp_id then seed for stable test output."""
    out: List[Tuple[str, int, str, dict]] = []
    for name in sorted(os.listdir(output_root)):
        full = os.path.join(output_root, name)
        if not os.path.isdir(full):
            continue
        m = _RUN_DIR_RE.match(name)
        if not m:
            continue
        summary_path = os.path.join(full, "summary.json")
        if not os.path.exists(summary_path):
            print(f"[aggregate] skipping {name}: no summary.json yet (run in progress?)")
            continue
        try:
            with open(summary_path) as f:
                summary = json.load(f)
        except (json.JSONDecodeError, OSError) as e:
            print(f"[aggregate] skipping {name}: malformed summary.json ({e})")
            continue
        out.append((m.group("exp_id"), int(m.group("seed")), full, summary))
    out.sort(key=lambda x: (x[0], x[1]))
    return out


def _row_for_run(exp_id: str, seed: int, summary: dict) -> Dict[str, object]:
    """Flatten one summary into a CSV/MD row."""
    final_macro = summary.get("final_macro") or {}
    macro_forg = summary.get("macro_forgetting") or {}
    row: Dict[str, object] = {
        "exp_id": exp_id,
        "seed": seed,
        "mode": summary.get("mode"),
        "lr_schedule": summary.get("lr_schedule"),
        "grounding_floor": summary.get("grounding_floor"),
        "replay": summary.get("replay"),
        "n_checkpoints": summary.get("n_checkpoints"),
        "collapse_indicator": summary.get("collapse_indicator"),
        "final_macro_answer_acc": summary.get("final_macro_answer_acc"),
    }
    for m in HEADLINE_METRICS:
        row[f"final_macro_{m}"] = final_macro.get(m)
    for m in HEADLINE_METRICS:
        row[f"macro_forgetting_{m}"] = macro_forg.get(m)
    return row


def _sort_key(row: Dict[str, object]) -> Tuple[float, float]:
    """Sort by collapse_indicator ascending (None last), then by
    final_macro_grounding_acc descending. Lower collapse = worse signal,
    so worst-case format collapse appears at the top of the table."""
    ci = row.get("collapse_indicator")
    ga = row.get("final_macro_grounding_acc@0.8")
    return (
        ci if isinstance(ci, (int, float)) else float("inf"),
        -ga if isinstance(ga, (int, float)) else float("inf"),
    )


def _fmt(v) -> str:
    if v is None:
        return ""
    if isinstance(v, float):
        return f"{v:.3f}"
    return str(v)


def write_outputs(rows: List[Dict[str, object]], output_root: str) -> Tuple[str, str]:
    csv_path = os.path.join(output_root, "_master_comparison.csv")
    md_path = os.path.join(output_root, "_master_comparison.md")
    fieldnames = list(rows[0].keys()) if rows else [
        "exp_id", "seed", "mode", "lr_schedule", "grounding_floor", "replay",
        "n_checkpoints", "collapse_indicator", "final_macro_answer_acc",
    ] + [f"final_macro_{m}" for m in HEADLINE_METRICS] \
      + [f"macro_forgetting_{m}" for m in HEADLINE_METRICS]

    with open(csv_path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for r in rows:
            w.writerow({k: r.get(k) for k in fieldnames})

    lines = []
    lines.append("| " + " | ".join(fieldnames) + " |")
    lines.append("| " + " | ".join(["---"] * len(fieldnames)) + " |")
    for r in rows:
        lines.append("| " + " | ".join(_fmt(r.get(k)) for k in fieldnames) + " |")
    with open(md_path, "w") as f:
        f.write("# Curriculum-v2 Ablation — Master Comparison\n\n")
        f.write(f"Generated by `qwenvl.experiments.aggregate` over `{output_root}`.\n\n")
        f.write(f"Sort order: collapse_indicator asc, then final_macro_grounding desc.\n\n")
        f.write("\n".join(lines) + "\n")
    return csv_path, md_path


def main(argv=None) -> int:
    p = argparse.ArgumentParser(prog="python -m qwenvl.experiments.aggregate",
                                description=__doc__)
    p.add_argument("--output_root", required=True,
                   help="Where the <exp_id>__seed<N>/ run dirs live.")
    args = p.parse_args(argv)

    if not os.path.isdir(args.output_root):
        print(f"ERROR: output_root not found: {args.output_root}")
        return 2

    runs = discover_runs(args.output_root)
    if not runs:
        print(f"[aggregate] no completed runs under {args.output_root}; "
              f"writing empty comparison tables.")
        rows = []
    else:
        rows = [_row_for_run(eid, seed, summary)
                for eid, seed, _, summary in runs]
        rows.sort(key=_sort_key)

    csv_path, md_path = write_outputs(rows, args.output_root)
    print(f"[aggregate] wrote: {csv_path}")
    print(f"[aggregate] wrote: {md_path}")
    print(f"[aggregate] {len(rows)} completed run(s) included.")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(main())
